from pathlib import Path
root = Path(__file__).resolve().parents[1]
assets = [('index.html','WEB_INDEX'),('style.css','WEB_STYLE'),('app.mjs','WEB_APP'),('image.mjs','WEB_IMAGE')]
lines = ['// Generated by tools/embed_web.py from web/dist.\n#pragma once\n#include <Arduino.h>\n']
for filename, symbol in assets:
    text = (root/'web/dist'/filename).read_text()
    assert ')PAPERWEB"' not in text
    lines.append(f'const char {symbol}[] PROGMEM = R"PAPERWEB({text})PAPERWEB";\n')
(root/'firmware/EpaperBLE/WebAssets.h').write_text('\n'.join(lines))
print('Embedded', ', '.join(name for name, _ in assets))
